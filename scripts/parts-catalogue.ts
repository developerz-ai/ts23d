// Generate the parts catalogue: recipes/_parts/README.md (name, description, params with defaults,
// thumbnail) and one zero-GPU beauty thumbnail per part in recipes/_parts/out/<part>.png.
// `--check` fails (exit 1) when the README is stale, without rendering.

import { mkdir } from 'node:fs/promises';
import {
  type AnyPart,
  type Asset,
  beauty,
  compile,
  defineAsset,
  type ParamInfo,
  type PartInfo,
} from '../src/index.ts';

const DIR = 'recipes/_parts';

/** A one-part asset so the renderer and QA see a part like any asset. */
export function partAsset(part: AnyPart): Asset {
  return defineAsset({
    name: `part_${part.info.name}`,
    kind: 'part',
    budget: { triangles: [200000, 100000, 50000] },
    glow: [{ parts: ['*_glow'] }],
    build(ctx) {
      part(ctx, part.info.name, {}, { upTo: 2 });
    },
  });
}

const fmt = (v: ParamInfo['default']): string =>
  typeof v === 'string' ? `'${v}'` : Array.isArray(v) ? `[${v.join(', ')}]` : String(v);

function paramCell(p: ParamInfo): string {
  const range =
    p.oneOf !== undefined
      ? ` (${p.oneOf.map(fmt).join(' \\| ')})`
      : p.min !== undefined || p.max !== undefined
        ? ` (${p.min ?? '…'}–${p.max ?? '…'}${p.unit ? ` ${p.unit}` : ''})`
        : '';
  return `\`${p.name}\` = ${fmt(p.default)}${range}${p.doc ? `: ${p.doc}` : ''}`;
}

/** The README body for these catalogue rows (sorted by the caller). */
export function renderIndex(rows: readonly PartInfo[]): string {
  const lines = [
    '# Parts kit',
    '',
    '<!-- generated by `bun run scripts/parts-catalogue.ts`; edit the parts, not this file -->',
    '',
    '**Search here before you write geometry.** Each part is a `definePart` (src/core/define-part.ts):',
    'typed params with real-scale defaults, validated, LOD-gated, cached per (params, LOD).',
    '',
    '```ts',
    "import { hex_bolt, hinge } from '../_parts/index.ts';",
    "hex_bolt(ctx, 'bolt_0', { size: 'M16', length: 0.06 }, { at: [1, 0, 0.5] }); // a named part",
    "const head = hex_bolt.mesh({ size: 'M10' }, ctx); // a mesh to place N times and merge",
    '```',
    '',
    `${rows.length} parts. How to define your own: [docs/idea/14-parts.md](../../docs/idea/14-parts.md).`,
    '',
    '| | Part | What | Params (default, range) |',
    '|---|---|---|---|',
  ];
  for (const r of rows)
    lines.push(
      `| ![${r.name}](out/${r.name}.png) | \`${r.name}\`<br>${r.tags.join(', ')} | ${r.description}${r.lod?.upTo !== undefined ? ` (LOD ≤ ${r.lod.upTo})` : ''} | ${r.params.map(paramCell).join('<br>')} |`,
    );
  return `${lines.join('\n')}\n`;
}

/** Write README + thumbnails; returns the paths written. */
export async function writeCatalogue(
  parts: readonly AnyPart[],
  rows: readonly PartInfo[],
): Promise<string[]> {
  await mkdir(`${DIR}/out`, { recursive: true });
  const written = [`${DIR}/README.md`];
  await Bun.write(`${DIR}/README.md`, renderIndex(rows));
  for (const p of parts) {
    const png = beauty(compile(partAsset(p)), { width: 320, height: 240, azDeg: -35, elDeg: 22 });
    const path = `${DIR}/out/${p.info.name}.png`;
    await Bun.write(path, png);
    written.push(path);
  }
  return written;
}

if (import.meta.main) {
  const { PARTS, catalogue } = await import('../recipes/_parts/index.ts');
  const rows = catalogue();
  if (process.argv.includes('--check')) {
    const now = await Bun.file(`${DIR}/README.md`)
      .text()
      .catch(() => '');
    if (now !== renderIndex(rows)) {
      console.error(
        `✗ parts-catalogue: ${DIR}/README.md is stale\n  fix: bun run scripts/parts-catalogue.ts`,
      );
      process.exitCode = 1;
    } else console.log('✔ parts-catalogue');
  } else {
    const out = await writeCatalogue(PARTS, rows);
    console.log(`✔ parts-catalogue: ${out.length} files under ${DIR}`);
  }
}
