// One-off generator: Hershey `.jhf` stroke fonts → TypeScript glyph tables in src/primitives/
// (font-hershey-*.ts), so the shipped library never reads files or fetches at runtime. Run once
// when a face is added: `bun scripts/fonts-hershey.ts <dir with the .jhf files>`. Source:
// https://github.com/kamalmostafa/hershey-fonts (hershey-fonts/*.jhf). The Hershey licence asks
// that its acknowledgements travel with the data, so every generated module carries them.

import { Ts23dError } from '../src/core/index.ts';

export interface FaceSpec {
  /** `TextFont` name, e.g. 'sans'. */
  readonly font: string;
  /** Exported constant, e.g. 'SANS'. */
  readonly constant: string;
  /** Source file stem, e.g. 'futural'. */
  readonly file: string;
  /** Hershey's own name for the face. */
  readonly title: string;
}

export const FACES: readonly FaceSpec[] = [
  { font: 'sans', constant: 'SANS', file: 'futural', title: 'Simplex Roman' },
  { font: 'serif', constant: 'SERIF', file: 'timesr', title: 'Complex Roman' },
  { font: 'script', constant: 'SCRIPT', file: 'scriptc', title: 'Complex Script' },
  { font: 'gothic', constant: 'GOTHIC', file: 'gothiceng', title: 'Gothic English' },
];

export const SOURCE = 'https://github.com/kamalmostafa/hershey-fonts';

/**
 * Glyph strings (bearing pair + coordinate pairs) of a `.jhf` file, index = char code − 32.
 * A trailing DEL record (127) is dropped. Records may wrap over several physical lines; the vertex count says where one ends.
 */
export function parseJhf(text: string): string[] {
  const lines = text.split(/\r?\n/);
  const out: string[] = [];
  let i = 0;
  while (i < lines.length) {
    let rec = lines[i++] ?? '';
    if (rec.trim() === '') continue;
    const count = Number.parseInt(rec.slice(5, 8), 10);
    if (!Number.isInteger(count) || count < 1)
      throw new Ts23dError('T3D_RECIPE_INVALID', {
        cause: `jhf record ${out.length + 1} has no vertex count: ${JSON.stringify(rec.slice(0, 12))}`,
        fix: 'pass an unmodified Hershey .jhf file (5-digit id, 3-digit count, then pairs)',
      });
    const want = 8 + 2 * count;
    while (rec.length < want && i < lines.length) rec += lines[i++] ?? '';
    if (rec.length < want)
      throw new Ts23dError('T3D_RECIPE_INVALID', {
        cause: `jhf record ${out.length + 1} is truncated (${rec.length} of ${want} chars)`,
        fix: 'download the .jhf file again; it was cut short',
      });
    out.push(rec.slice(8, want));
  }
  if (out.length < 95)
    throw new Ts23dError('T3D_RECIPE_INVALID', {
      cause: `jhf file has ${out.length} glyphs, expected 95 (ASCII 32–126; a 96th, DEL, is dropped)`,
      fix: 'use one of the ASCII-ordered faces (futural, timesr, scriptc, gothiceng, …)',
    });
  return out.slice(0, 95);
}

/** The TypeScript module for one face. */
export function fontModule(face: FaceSpec, glyphs: readonly string[]): string {
  const rows = glyphs.map(
    (g, k) => `  ${JSON.stringify(g)}, // ${JSON.stringify(String.fromCharCode(32 + k))}`,
  );
  return `${[
    `// Hershey ${face.title} stroke font (${face.file}.jhf), ASCII 32–126, for text({ font: '${face.font}' }).`,
    '// Generated by scripts/fonts-hershey.ts; do not edit by hand.',
    `// Source: ${SOURCE} (hershey-fonts/${face.file}.jhf).`,
    '// Licence (Hershey font data; free for any purpose, commercial or otherwise, provided that):',
    '// - The Hershey Fonts were originally created by Dr. A. V. Hershey while working at the',
    '//   U. S. National Bureau of Standards.',
    '// - The format of the Font data in this distribution was originally created by James Hurt,',
    '//   Cognition, Inc., 900 Technology Park Drive, Billerica, MA 01821',
    '//   (mit-eddie!ci-dandelion!hurt).',
    "// Entry = Hurt's glyph string: left and right bearing, then x y pairs (char code − 82, y down),",
    "// ' R' lifts the pen. Cap height 21 units, baseline y = 9.",
    '',
    `export const ${face.constant}: readonly string[] = [`,
    ...rows,
    '];',
  ].join('\n')}\n`;
}

if (import.meta.main) {
  const dir = process.argv[2];
  if (!dir)
    throw new Ts23dError('T3D_RECIPE_INVALID', {
      cause: 'no .jhf directory given',
      fix: `bun scripts/fonts-hershey.ts <dir>; get the files from ${SOURCE}/tree/master/hershey-fonts`,
    });
  const paths: string[] = [];
  for (const face of FACES) {
    const glyphs = parseJhf(await Bun.file(`${dir}/${face.file}.jhf`).text());
    const path = `src/primitives/font-hershey-${face.font}.ts`;
    await Bun.write(path, fontModule(face, glyphs));
    paths.push(path);
  }
  // House formatting, so a re-run reproduces the committed files byte for byte.
  Bun.spawnSync(['bunx', 'biome', 'format', '--write', ...paths], { stdout: 'inherit' });
  console.log(`wrote ${paths.join(', ')}`);
}
