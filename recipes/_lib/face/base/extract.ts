// Regenerates `hm08-bust.ts` from the MakeHuman hm08 base mesh (CC0, see LICENSE.md): fetches the
// pinned upstream OBJ (or reads a local copy), checks its sha256, keeps the `body` group's quads
// above the chest (head, neck, shoulders, arm stubs), converts MakeHuman's decimetres / Y up /
// +Z front to metres / Z up / +X front, quantises positions to uint16 per axis and writes them
// and the quad indices as base64. Run: `bun recipes/_lib/face/base/extract.ts [base.obj]`.

export const HM08_URL =
  'https://raw.githubusercontent.com/makehumancommunity/makehuman/3c701a8e52f09e69922e8b598d23be2d7dfc49e3/makehuman/data/3dobjs/base.obj';
export const HM08_SHA256 = '8e761e6624b8f54536409135d1636da63b32486a90d4897f84e121d144f6fb4c';

/** Kept region (metres, ts23d axes): everything above the chest, inside the arm stubs. */
const KEEP = { zMin: 0.33, yMax: 0.3 };

async function source(path: string | undefined): Promise<string> {
  const bytes = path
    ? new Uint8Array(await Bun.file(path).arrayBuffer())
    : new Uint8Array(await (await fetch(HM08_URL)).arrayBuffer());
  const hash = new Bun.CryptoHasher('sha256').update(bytes).digest('hex');
  if (hash !== HM08_SHA256)
    throw new Error(`base.obj sha256 ${hash} ≠ pinned ${HM08_SHA256} (${HM08_URL})`);
  return new TextDecoder().decode(bytes);
}

function b64(bytes: Uint8Array): string {
  return Buffer.from(bytes).toString('base64');
}

async function main(): Promise<void> {
  const text = await source(process.argv[2]);
  const V: number[][] = [];
  const quads: number[][] = [];
  let group = '';
  for (const line of text.split('\n')) {
    const t = line.trim().split(/\s+/);
    if (t[0] === 'v') V.push([+(t[3] ?? 0) * 0.1, +(t[1] ?? 0) * 0.1, +(t[2] ?? 0) * 0.1]);
    else if (t[0] === 'g') group = t[1] ?? '';
    else if (t[0] === 'f' && group === 'body')
      quads.push(t.slice(1).map((s) => Number.parseInt(s, 10) - 1));
  }
  const inside = (i: number): boolean => {
    const p = V[i] ?? [0, 0, 0];
    return (p[2] ?? 0) > KEEP.zMin && Math.abs(p[1] ?? 0) < KEEP.yMax;
  };
  const kept = quads.filter((q) => q.length === 4 && q.every(inside));
  const remap = new Map<number, number>();
  for (const q of kept) for (const i of q) if (!remap.has(i)) remap.set(i, remap.size);
  const lo = [Infinity, Infinity, Infinity];
  const hi = [-Infinity, -Infinity, -Infinity];
  for (const i of remap.keys())
    for (let k = 0; k < 3; k++) {
      lo[k] = Math.min(lo[k] ?? 0, V[i]?.[k] ?? 0);
      hi[k] = Math.max(hi[k] ?? 0, V[i]?.[k] ?? 0);
    }
  const pos = new Uint16Array(remap.size * 3);
  for (const [i, j] of remap)
    for (let k = 0; k < 3; k++) {
      const t = ((V[i]?.[k] ?? 0) - (lo[k] ?? 0)) / ((hi[k] ?? 1) - (lo[k] ?? 0));
      pos[j * 3 + k] = Math.round(t * 65535);
    }
  const idx = new Uint16Array(kept.length * 4);
  kept.forEach((q, f) => {
    q.forEach((i, k) => {
      idx[f * 4 + k] = remap.get(i) ?? 0;
    });
  });
  const r = (v: number): number => Math.round(v * 1e5) / 1e5;
  const out = `// GENERATED by extract.ts from the MakeHuman hm08 base mesh (CC0 1.0, see LICENSE.md) — do not
// edit. ${remap.size} vertices, ${kept.length} quads: head, neck, shoulders and arm stubs, metres,
// Z up, +X front; positions uint16 per axis over [lo, hi], quads uint16 ×4, both base64 (LE).

export const HM08_BUST = {
  url: '${HM08_URL}',
  sha256: '${HM08_SHA256}',
  vertices: ${remap.size},
  quads: ${kept.length},
  lo: [${lo.map(r).join(', ')}],
  hi: [${hi.map(r).join(', ')}],
  positions:
    '${b64(new Uint8Array(pos.buffer))}',
  indices:
    '${b64(new Uint8Array(idx.buffer))}',
} as const;
`;
  await Bun.write(new URL('./hm08-bust.ts', import.meta.url), out);
  console.log(`hm08-bust.ts: ${remap.size} vertices, ${kept.length} quads`);
}

if (import.meta.main) await main();
