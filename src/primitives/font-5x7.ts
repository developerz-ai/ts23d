const group = (c: string): number =>
  /[A-Z]/.test(c) ? 0 : /[0-9]/.test(c) ? 1 : /[А-ЯЁ]/.test(c) ? 3 : 2;
/** Every character `text` can set (lower case is accepted and set as upper case). */
export const SUPPORTED_CHARS = Object.keys(GLYPHS)
  .filter((c) => c !== ' ')
  .sort((a, b) => group(a) - group(b) || (a < b ? -1 : a > b ? 1 : 0))
  .join('')
  .concat(' and space');
