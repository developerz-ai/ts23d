// The Godot 4 emitter behind `godotShaderSource`: prints a spatial .gdshader with the same uniforms
// as the three.js module. Values come pre-validated from shader.ts.

import type { ShaderParams } from './shader.ts';
import type { UvRect } from './trim-sheet.ts';

const f = (n: number): string => (Number.isInteger(n) ? `${n}.0` : `${+n.toFixed(6)}`);
const rect = (r: UvRect): string =>
  `in_rect(UV, vec4(${f(r.u0)}, ${f(r.v0)}, ${f(r.u1)}, ${f(r.v1)}))`;

export function godotSource(p: ShaderParams): string {
  const modes = ['blend_mix', 'depth_draw_opaque', p.cutout ? 'cull_disabled' : 'cull_back'];
  const weight = p.windAttribute
    ? 'CUSTOM0.x /* import _WIND into CUSTOM0 (glTF import: custom attribute mapping) */'
    : 'smoothstep(0.0, wind_height, VERTEX.z)';
  return `// Generated by @developerz-ai/ts23d godotShaderSource(). A starting point your project owns:
// assign it to a ShaderMaterial and set albedo_tex / normal_tex / orm_tex from the GLB's
// ts23d_* material (or the shared trim_sheet_{albedo,normal,orm}.png). Godot 4.x.
shader_type spatial;
render_mode ${modes.join(', ')};

uniform sampler2D albedo_tex : source_color, filter_linear_mipmap, repeat_enable;
uniform sampler2D normal_tex : hint_normal, filter_linear_mipmap, repeat_enable;
uniform sampler2D orm_tex : hint_default_white, filter_linear_mipmap, repeat_enable;

uniform float night : hint_range(0.0, 1.0) = 0.0;
uniform float wind_strength = ${f(p.windStrength)};
uniform float wind_height = ${f(p.windHeight)};
uniform float wind_hz = ${f(p.windHz)};
uniform vec3 glow_color : source_color = vec3(${f(p.glow[0])}, ${f(p.glow[1])}, ${f(p.glow[2])});
uniform float glow_ratio : hint_range(0.0, 1.0) = ${f(p.glowRatio)};
uniform float glow_intensity = ${f(p.glowIntensity)};
uniform float wear : hint_range(0.0, 1.0) = ${f(p.wear)};
uniform float grime_height = ${f(p.grimeHeight)};

varying vec3 world_pos;

float in_rect(vec2 uv, vec4 r) {
	float u = fract(uv.x);
	return step(r.x, u) * step(u, r.z) * step(r.y, uv.y) * step(uv.y, r.w);
}

float hash13(vec3 p) {
	p = fract(p * 0.1031);
	p += dot(p, p.zyx + 31.32);
	return fract((p.x + p.y) * p.z);
}

void vertex() {
	// Wind sway: mesh-local Z is the authored up axis; sway in local XY.
	float weight = ${weight};
	float phase = VERTEX.x * 0.7 + VERTEX.y * 0.45;
	float sway = sin(TIME * wind_hz * 6.2832 + phase) * wind_strength * weight * 0.1;
	VERTEX.xy += vec2(sway, sway * 0.6);
	world_pos = (MODEL_MATRIX * vec4(VERTEX, 1.0)).xyz;
}

void fragment() {
	vec4 base = texture(albedo_tex, UV);
	vec3 orm = texture(orm_tex, UV).rgb;
	float ground = 1.0 - smoothstep(0.0, grime_height, world_pos.y);
	float grime = clamp(wear * max((1.0 - orm.r) * 1.5, ground), 0.0, 1.0);
	ALBEDO = base.rgb * COLOR.rgb * (1.0 - grime * 0.45);
	AO = orm.r;
	ROUGHNESS = clamp(orm.g + grime * 0.2, 0.0, 1.0);
	METALLIC = orm.b * (1.0 - grime);
	NORMAL_MAP = texture(normal_tex, UV).rgb;
${p.cutout ? '\tALPHA = base.a;\n\tALPHA_SCISSOR_THRESHOLD = 0.5;\n' : p.blend ? '\tALPHA = base.a * 0.6;\n' : ''}
	// Window glow: dark panes in window cells, or the glass strip; 1.5 m world slots, glow_ratio lit.
	float luma = dot(base.rgb, vec3(0.2126, 0.7152, 0.0722));
	float panes = (${p.glowRects.map(rect).join(' + ')}) * step(luma, 0.3);
	float mask = max(panes, ${rect(p.glassRect)});
	float lit = step(hash13(floor(world_pos / 1.5)), glow_ratio);
	EMISSION = glow_color * mask * lit * night * glow_intensity;
}
`;
}
