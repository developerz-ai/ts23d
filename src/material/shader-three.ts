// The three.js TSL emitter behind `threeMaterialSource`: prints a self-contained TypeScript module
// for three r18x (`three/webgpu` + `three/tsl`). Values come pre-validated from shader.ts.

import type { ShaderParams } from './shader.ts';
import type { UvRect } from './trim-sheet.ts';

const f = (n: number): string => (Number.isInteger(n) ? `${n}.0` : `${+n.toFixed(6)}`);

const rectNode = (r: UvRect): string => `inRect(${f(r.u0)}, ${f(r.v0)}, ${f(r.u1)}, ${f(r.v1)})`;

export function threeSource(p: ShaderParams): string {
  const weight = p.windAttribute
    ? "attribute('_wind', 'float')"
    : 'smoothstep(float(0), uWindHeight, positionLocal.z)';
  const glowCells = p.glowRects.map(rectNode).join('.add(') + ')'.repeat(p.glowRects.length - 1);
  return `// Generated by @developerz-ai/ts23d threeMaterialSource(). A starting point your project owns:
// edit freely. Needs three r18x (WebGPURenderer + TSL). ts23d itself has no three dependency.
//
// Usage: const gltf = await loader.loadAsync('tank.glb'); upgradeTrimMaterials(gltf.scene);
//        trim.uniforms.night.value = 1; // at dusk

import { DoubleSide, type Material, type Mesh, MeshStandardMaterial, MeshStandardNodeMaterial, type Object3D, type Texture } from 'three/webgpu';
import { attribute, color, float, floor, fract, hash, max, normalMap, positionLocal, positionWorld, sin, smoothstep, step, texture, time, uniform, uv, vec3, vertexColor } from 'three/tsl';

export interface TrimMaps {
  readonly albedo: Texture;
  readonly normal: Texture | null;
  readonly orm: Texture | null;
}

/** Shared uniforms: one set drives every trim material, so a scene-wide night switch is one write. */
export const uniforms = {
  night: uniform(0),
  windStrength: uniform(${f(p.windStrength)}),
  windHeight: uniform(${f(p.windHeight)}),
  windHz: uniform(${f(p.windHz)}),
  glowColor: uniform(color(${f(p.glow[0])}, ${f(p.glow[1])}, ${f(p.glow[2])})),
  glowRatio: uniform(${f(p.glowRatio)}),
  glowIntensity: uniform(${f(p.glowIntensity)}),
  wear: uniform(${f(p.wear)}),
  grimeHeight: uniform(${f(p.grimeHeight)}),
};

/** 1 inside a trim-sheet UV rect (U wraps: strips tile along U). */
function inRect(u0: number, v0: number, u1: number, v1: number) {
  const t = uv();
  const u = fract(t.x);
  return step(u0, u).mul(step(u, u1)).mul(step(v0, t.y)).mul(step(t.y, v1));
}

export function createTrimMaterial(maps: TrimMaps, cutout = ${p.cutout}): MeshStandardNodeMaterial {
  const { night, windStrength: uWindStrength, windHeight: uWindHeight, windHz, glowColor, glowRatio, glowIntensity, wear, grimeHeight } = uniforms;
  const m = new MeshStandardNodeMaterial();
  const base = texture(maps.albedo, uv());
  const orm = maps.orm ? texture(maps.orm, uv()) : vec3(1, 0.8, 0);
  const tint = vertexColor();

  // Wear / grime: cavities (low AO) and the first metres above the ground get darker and rougher.
  const ground = float(1).sub(smoothstep(float(0), grimeHeight, positionWorld.y));
  const grime = wear.mul(max(float(1).sub(orm.x).mul(1.5), ground)).clamp(0, 1);
  m.colorNode = base.rgb.mul(tint.rgb).mul(float(1).sub(grime.mul(0.45)));
  m.roughnessNode = orm.y.add(grime.mul(0.2)).clamp(0, 1);
  m.metalnessNode = orm.z.mul(float(1).sub(grime));
  m.aoNode = orm.x;
  if (maps.normal) m.normalNode = normalMap(texture(maps.normal, uv()));
  if (cutout) {
    m.opacityNode = base.a;
    m.alphaTest = 0.5;
    m.side = DoubleSide;
  }

  // Wind sway (authored Z-up, so sway in local XY), phase-shifted across the crown.
  const windWeight = ${weight};
  const phase = positionLocal.x.mul(0.7).add(positionLocal.y.mul(0.45));
  const sway = sin(time.mul(windHz).mul(6.2832).add(phase)).mul(uWindStrength).mul(windWeight).mul(0.1);
  m.positionNode = positionLocal.add(vec3(sway, sway.mul(0.6), 0));

  // Window glow: dark pane texels in window cells, or the glass strip; a world-space hash lights
  // \`glowRatio\` of the 1.5 m window slots; scaled by \`night\`.
  const luma = base.r.mul(0.2126).add(base.g.mul(0.7152)).add(base.b.mul(0.0722));
  const panes = ${glowCells}.mul(step(luma, 0.3));
  const mask = max(panes, ${rectNode(p.glassRect)});
  const slot = floor(positionWorld.div(1.5));
  const lit = step(hash(slot.x.mul(73).add(slot.y.mul(157)).add(slot.z.mul(311))), glowRatio);
  m.emissiveNode = glowColor.mul(mask).mul(lit).mul(night).mul(glowIntensity);
  return m;
}

/** Replace every ts23d_* material under \`root\` with the node material, reusing the GLB's maps. */
export function upgradeTrimMaterials(root: Object3D): void {
  const cache = new Map<Material, MeshStandardNodeMaterial>();
  root.traverse((o) => {
    const mesh = o as Mesh;
    const old = mesh.isMesh ? mesh.material : null;
    if (!(old instanceof MeshStandardMaterial) || !old.name.startsWith('ts23d') || !old.map) return;
    const next = cache.get(old) ?? createTrimMaterial({ albedo: old.map, normal: old.normalMap, orm: old.roughnessMap }, old.alphaTest > 0);
    next.name = old.name;
    cache.set(old, next);
    mesh.material = next;
  });
}
`;
}
